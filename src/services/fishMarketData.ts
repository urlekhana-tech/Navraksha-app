export const getFishMarketRates = (portName: string = 'Mangalore Old Port'): FishSpeciesRate[] => {
  // Return adjusted rates based on port
  return FISH_MARKET_RATES.map((item) => {
    let multiplier = 1.0;
    if (portName.includes('Mumbai')) multiplier = 1.15;
    else if (portName.includes('Kochi')) multiplier = 0.96;
    else if (portName.includes('Chennai')) multiplier = 1.04;
    else if (portName.includes('Veraval')) multiplier = 0.88;

    const currentRate = Math.round(item.currentRate * multiplier);
    const minRate = Math.round(item.minRate * multiplier);
    const maxRate = Math.round(item.maxRate * multiplier);
    const previousRate = Math.round(item.previousRate * multiplier);

    return {
      ...item,
      portName,
      currentRate,
      minRate,
      maxRate,
      previousRate,
    };
  });
};
